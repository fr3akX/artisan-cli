package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"

	"github.com/fr3akX/artisan-cli/internal/securefile"
)

func main() {
	if len(os.Args) != 3 {
		fatalf("usage: embedskill SOURCE DESTINATION")
	}
	contents, err := os.ReadFile(os.Args[1])
	if err != nil {
		fatalf("read source: %v", err)
	}
	generated := []byte("// Code generated by embedskill; DO NOT EDIT.\n\npackage skill\n\nvar Content = []byte(" + strconv.Quote(string(contents)) + ")\n")
	generated, err = format.Source(generated)
	if err != nil {
		fatalf("format generated source: %v", err)
	}
	if err := atomicWrite(os.Args[2], generated); err != nil {
		fatalf("write destination: %v", err)
	}
}

func atomicWrite(destination string, contents []byte) error {
	return atomicWriteWithOperations(destination, contents,
		func(file *os.File) error { return file.Sync() },
		atomicReplace,
		securefile.SyncParentDirectory,
	)
}

func atomicWriteWithOperations(
	destination string,
	contents []byte,
	syncFile func(*os.File) error,
	replace func(string, string) error,
	syncParent func(string) error,
) (returnedErr error) {
	directory := filepath.Dir(destination)
	file, err := os.CreateTemp(directory, "."+filepath.Base(destination)+".tmp-*")
	if err != nil {
		return err
	}
	temporary := file.Name()
	defer func() {
		_ = file.Close()
		_ = os.Remove(temporary)
	}()
	if err := file.Chmod(0o644); err != nil {
		return err
	}
	if _, err := file.Write(contents); err != nil {
		return err
	}
	if err := syncFile(file); err != nil {
		return fmt.Errorf("sync generated skill: %w", err)
	}
	if err := file.Close(); err != nil {
		return err
	}
	if err := replace(temporary, destination); err != nil {
		return err
	}
	if err := syncParent(directory); err != nil {
		return &securefile.ReplacementError{Err: fmt.Errorf("sync generated skill directory: %w", err)}
	}
	return nil
}

func fatalf(format string, args ...any) {
	_, _ = fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
